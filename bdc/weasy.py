
import base64
import csv
from io import BytesIO
from pathlib import Path

import segno
from django.conf import settings
from django.template.loader import render_to_string
from django.utils.translation import get_language_from_request, gettext_lazy as _
from weasyprint import HTML

empty_items = ['-', '--', '_', '__', '---', '***', '/', 
    '?', '??', '???', ' ', '.', '..', '...', '',
    'Aucune', 'Non'
]

def create_bdc_items_pdf(bdc):

    crm = _("Generated by ")
    url = "https://new.emarches.com/bdc/"
    
    if bdc : url += f"{bdc.id}"

    qr_buffer = BytesIO()
    segno.make(url, error='M').save(qr_buffer, kind='svg', scale=8)
    qr_svg_base64 = base64.b64encode(qr_buffer.getvalue()).decode()
    qr_data_uri = f"data:image/svg+xml;base64,{ qr_svg_base64 }"

    context = {
        "bdc": bdc,
        'empty_items'  : empty_items,
        "crm": crm + ' ' + 'eMarches.com',
        "qr_code": qr_data_uri,
    }

    html_string = render_to_string("bdc/bdc-articles-pdf.html", context)

    pdf_file_name = f'eMarches.com-{ bdc.chrono }-items.pdf'
    output_dir = Path(settings.FILES_MEDIA_ROOT) / "bdc" / "items" / "pdf" / f"{ bdc.id }"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / f"{ pdf_file_name }"

    static_dir  = Path(settings.BASE_DIR) / "static"
    static_uri  = static_dir.resolve().as_uri()

    html_string = html_string.replace('/static/', f'{static_uri}/')

    HTML(string=html_string).write_pdf(target=output_path)
    
    return output_path


def generate_items_csv(request, bdc, dir_name=None, file_name=None):

    if not bdc: 
        return None

    try:
        lang_code = get_language_from_request(request, check_path=True)
        if lang_code is None or lang_code == '': lang_code = 'en'

        csv_file_name = file_name if file_name else f'eMarches.com-PO-{ bdc.chrono }-{lang_code}.csv'
        output_dir = dir_name if dir_name else Path(settings.FILES_MEDIA_ROOT) / "bdc" / "items" / "csv" / f"{ bdc.id }"        

        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / f"{ csv_file_name }"

        with open(output_path, "w", newline="", encoding="utf-8-sig") as f:
            writer = csv.writer(f)
            writer.writerow([
                _('Number'), 
                _('Title'), 
                _('UOM'), 
                _('Quantity'), 
                _('VAT') + '%', 
                _('Specifications'), 
                _('Warranties'), 
                ])

            for item in bdc.articles.all():
                writer.writerow([
                    item.number,
                    item.title,
                    item.uom,
                    item.quantity,
                    item.vat_percent,
                    item.specifications,
                    item.warranties,
                ])

        return output_path

    except Exception as xc:
        traceback.print_exc()

    return None


